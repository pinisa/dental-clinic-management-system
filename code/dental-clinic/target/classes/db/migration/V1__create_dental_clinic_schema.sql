CREATE TABLE IF NOT EXISTS patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    coverage_type VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS patient_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medical_history TEXT,
    allergies VARCHAR(255),
    emergency_contact VARCHAR(100) NOT NULL,
    patient_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_profile_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS dentist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150),
    specialization VARCHAR(150),
    license_number VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS appointment_queues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_number VARCHAR(50),
    service_type VARCHAR(100),
    base_price DOUBLE PRECISION,
    final_price DOUBLE PRECISION,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    patient_id BIGINT,
    dentist_id BIGINT,
    CONSTRAINT fk_queue_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_queue_dentist FOREIGN KEY (dentist_id) REFERENCES dentist(id)
);

CREATE TABLE IF NOT EXISTS treatment_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnosis_note TEXT NOT NULL,
    total_cost DOUBLE PRECISION NOT NULL,
    record_date TIMESTAMP NOT NULL,
    patient_id BIGINT NOT NULL,
    dentist_id BIGINT NOT NULL,
    appointment_queue_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_treatment_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_treatment_dentist FOREIGN KEY (dentist_id) REFERENCES dentist(id),
    CONSTRAINT fk_treatment_queue FOREIGN KEY (appointment_queue_id) REFERENCES appointment_queues(id)
);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_date_time TIMESTAMP NOT NULL,
    service_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    patient_id BIGINT NOT NULL,
    dentist_id BIGINT NOT NULL,
    CONSTRAINT fk_appointment_patient FOREIGN KEY (patient_id) REFERENCES patients(id),
    CONSTRAINT fk_appointment_dentist FOREIGN KEY (dentist_id) REFERENCES dentist(id)
);

CREATE INDEX IF NOT EXISTS idx_queue_patient ON appointment_queues(patient_id);
CREATE INDEX IF NOT EXISTS idx_queue_dentist_status ON appointment_queues(dentist_id, status);
CREATE INDEX IF NOT EXISTS idx_treatment_patient ON treatment_records(patient_id);
CREATE INDEX IF NOT EXISTS idx_treatment_dentist ON treatment_records(dentist_id);
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments(patient_id);
CREATE INDEX IF NOT EXISTS idx_appointments_dentist_datetime ON appointments(dentist_id, appointment_date_time);
